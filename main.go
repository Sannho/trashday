package main

import (
	_ "embed"
	"encoding/json"
	"fmt"
	"log"
	"strings"

	webview2 "github.com/jchv/go-webview2"
)

var (
	//go:embed index.html
	page string
	//go:embed ui.css
	css string // generated by build.ps1 with the Tailwind CLI
)

type targetInfo struct {
	Key   string `json:"key"` // English name: stable across languages, used for the saved selection
	Group string `json:"group"`
	Name  string `json:"name"`
	Desc  string `json:"desc"`
	Quick bool   `json:"quick"`
}

func (t tr) in(lang string) string {
	if lang == "fr" {
		return t.FR
	}
	return t.EN
}

func main() {
	list := targets()

	w := webview2.NewWithOptions(webview2.WebViewOptions{
		AutoFocus: true,
		WindowOptions: webview2.WindowOptions{
			Title:  "TrashDay",
			Width:  440,
			Height: 760,
			IconId: 2, // icon group resource ID assigned by rsrc (manifest is 1)
			Center: true,
		},
	})
	if w == nil {
		log.Fatal("WebView2 indisponible : installez le runtime WebView2 d'Edge.")
	}
	defer w.Destroy()

	// call runs JS on the UI thread with JSON-encoded arguments.
	call := func(fn string, args ...any) {
		b, _ := json.Marshal(args)
		js := fmt.Sprintf("%s(...%s)", fn, b)
		w.Dispatch(func() { w.Eval(js) })
	}

	w.Bind("goTargets", func(lang string) []targetInfo {
		out := make([]targetInfo, len(list))
		for i, t := range list {
			out[i] = targetInfo{t.Name.EN, t.Group.in(lang), t.Name.in(lang), t.Desc.in(lang), t.Quick}
		}
		return out
	})

	// Bindings run on the UI thread, so cleaning happens in a goroutine and
	// reports back through onProgress / onDone. With dry set, nothing is deleted:
	// Freed is then the size that would be freed.
	w.Bind("goClean", func(ids []int, dry bool) {
		go func() {
			var total Result
			for _, id := range ids {
				if id < 0 || id >= len(list) {
					continue
				}
				call("onProgress", id, nil)
				r := cleanTarget(list[id], dry)
				total.add(r)
				call("onProgress", id, r)
			}
			call("onDone", total)
		}()
	})

	// SetHtml has no base URL, so the stylesheet is inlined instead of linked.
	w.SetHtml(strings.Replace(page, `<link rel="stylesheet" href="ui.css">`, "<style>"+css+"</style>", 1))
	w.Run()
}
